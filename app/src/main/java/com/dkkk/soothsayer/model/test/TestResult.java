package com.dkkk.soothsayer.model.test;

/**
 * Модель результата теста (TestResult).
 *
 * Используется для хранения информации о результате прохождения теста пользователем.
 * Представляет собой готовый результат, который отображается после завершения теста.
 *
 * Применяется в:
 * - тесте "Какая ты ведьма" (Witch)
 * - тесте "Какой камень тебе подходит" (Stone)
 * - отображении финального экрана с результатом
 *
 * @author Soothsayer Team
 * @version 1.0
 */
public class TestResult {

    /** Заголовок результата (например: "Ведьма Воды" или "Аквамарин") */
    public String title;

    /** Полное текстовое описание результата с характеристиками и рекомендациями */
    public String text;

    /** Имя файла изображения (без расширения), соответствующего результату
     *  (например: "witch_water", "stone_1" и т.д.) */
    public String image;

    /**
     * Конструктор модели результата теста.
     *
     * @param title заголовок результата (название ведьмы или камня)
     * @param text подробное описание результата (значение, свойства, рекомендации)
     * @param image имя ресурса изображения для отображения результата
     */
    public TestResult(String title, String text, String image) {
        this.title = title;
        this.text = text;
        this.image = image;
    }
}