package com.dkkk.soothsayer.model.test;

/**
 * Модель варианта ответа (Answer).
 *
 * Представляет один вариант ответа на вопрос теста.
 * Содержит текст ответа и его "вес" (score), который определяет,
 * к какому типу результата относится данный ответ.
 *
 * При прохождении теста пользователь выбирает один из вариантов ответа,
 * система запоминает его score, а в конце подсчитывает,
 * какой score встречался чаще всего — это и будет тип результата.
 *
 * Применяется в:
 * - тесте "Какая ты ведьма" (Witch)
 * - тесте "Какой камень тебе подходит" (Stone)
 * - адаптере для отображения вариантов ответов в RadioGroup
 * - логике подсчёта результата в TestViewModel
 *
 * @author Soothsayer Team
 * @version 1.0
 */
public class Answer {

    /** Уникальный идентификатор варианта ответа в базе данных */
    public int id;

    /** Идентификатор вопроса, к которому относится данный ответ (внешний ключ) */
    public int questionId;

    /** Текст варианта ответа, отображаемый пользователю */
    public String text;

    /**
     * Числовое значение ответа (тип результата).
     *
     * Для теста "witch" возможные значения:
     * 1 = Ведьма Воды
     * 2 = Ведьма Огня
     * 3 = Ведьма Земли
     * 4 = Ведьма Воздуха
     * 5 = Ведьма Света
     * 6 = Ведьма Тьмы
     *
     * Для теста "stone" возможные значения:
     * 1 = Аквамарин
     * 2 = Рубин
     * 3 = Малахит
     * 4 = Аметист
     * 5 = Янтарь
     * 6 = Лабрадор
     */
    public int score;

    /**
     * Конструктор модели варианта ответа.
     *
     * @param id уникальный идентификатор ответа
     * @param questionId идентификатор вопроса, к которому относится ответ
     * @param text варианта ответа для отображения пользователю
     * @param score числовое значение, определяющее тип результата
     */
    public Answer(int id, int questionId, String text, int score) {
        this.id = id;
        this.questionId = questionId;
        this.text = text;
        this.score = score;
    }
}