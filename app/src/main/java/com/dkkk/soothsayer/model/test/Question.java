package com.dkkk.soothsayer.model.test;

/**
 * Модель вопроса теста (Question).
 *
 * Представляет один вопрос, отображаемый пользователю во время прохождения теста.
 * Содержит только базовую информацию: идентификатор и текст вопроса.
 *
 * Применяется в:
 * - тесте "Какая ты ведьма" (Witch)
 * - тесте "Какой камень тебе подходит" (Stone)
 * - адаптере для отображения списка вопросов
 * - передаче данных между Activity и фрагментами
 *
 * @author Soothsayer Team
 * @version 1.0
 */
public class Question {

    /** Уникальный идентификатор вопроса в базе данных */
    public int id;

    /** Текст вопроса, отображаемый пользователю */
    public String text;

    /**
     * Конструктор модели вопроса.
     *
     * @param id уникальный идентификатор вопроса (соответствует полю _id в таблице questions)
     * @param text текст вопроса для отображения (например: "Какое время суток тебе ближе всего?")
     */
    public Question(int id, String text) {
        this.id = id;
        this.text = text;
    }
}