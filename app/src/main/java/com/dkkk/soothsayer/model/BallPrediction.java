package com.dkkk.soothsayer.model;

/**
 * Модель предсказания для магического шара (BallPrediction).
 *
 * Представляет одно предсказание, хранящееся в базе данных.
 * Используется для отображения случайного ответа при нажатии на магический шар.
 *
 * Предсказания бывают разных типов:
 * - позитивные (исполнение желания, удача, радость)
 * - нейтральные (неопределённость, совет подождать)
 * - негативные (предупреждение, отказ судьбы)
 *
 * Применяется в:
 * - магическом шаре предсказаний (BallActivity)
 * - репозитории BallRepository (получение случайного предсказания)
 * - адаптере для истории предсказаний (если будет реализовано)
 *
 */
public class BallPrediction {

    /** Уникальный идентификатор предсказания в базе данных */
    public int id;

    /**
     * Текст предсказания, отображаемый пользователю.
     *
     * Примеры предсказаний:
     * - "Да, именно так и случится. Вселенная уже начала приводить это в движение."
     * - "Нет, не жди этого в ближайшее время. Лучше переключись на другие цели."
     * - "Пока неясно, попробуй задать вопрос позже, когда энергия прояснится."
     */
    public String text;

    /**
     * Конструктор модели предсказания.
     *
     * @param id уникальный идентификатор предсказания (соответствует полю _id в таблице ball_predictions)
     * @param text текст предсказания, который увидит пользователь
     */
    public BallPrediction(int id, String text) {
        this.id = id;
        this.text = text;
    }
}