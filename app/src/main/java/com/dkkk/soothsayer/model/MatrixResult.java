package com.dkkk.soothsayer.model;

/**
 * Модель результата расчёта матрицы судьбы.
 *
 * Содержит:
 * - числовые позиции (p1–p92) — результат математических расчётов
 * - текстовые значения, полученные из базы данных
 *
 * Используется как единый объект для передачи данных
 * между ViewModel и UI (архитектура MVVM).
 */
public class MatrixResult {

    /** Основные рассчитанные позиции матрицы */
    public int p1, p2, p3, p4, p6, p7, p8, p9, p10;

    /** Дополнительные вычисленные позиции (углы и связки) */
    public int p21, p22, p41, p42, p51, p52, p53, p71, p72, p91, p92;

    /** Текстовые интерпретации значений из базы данных */

    /** Характер человека */
    public String character;

    /** Родительская энергия / влияние */
    public String parents;

    /** Таланты и способности */
    public String talent;

    /** Финансовая энергия */
    public String finance;

    /** Сфера заработка */
    public String earnings;

    /** Идеальный партнёр */
    public String partner;

    /** Кармический хвост */
    public String tail;

    /** Духовная карма родителей */
    public String spirit;

    /** Материальная карма / денежный канал */
    public String money;
}